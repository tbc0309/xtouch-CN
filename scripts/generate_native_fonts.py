"""Generate native text sizes for small and large displays; font inputs stay local."""
import argparse,re,shutil,subprocess,tempfile
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from generate_text_fonts import ranges
ROOT=Path(__file__).resolve().parents[1]
def points(path):return {int(c,16) for c in re.findall(r'/\* U\+([0-9A-Fa-f]+)',path.read_text('utf-8'))}
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--font',type=Path,required=True);p.add_argument('--fallback-font',type=Path,action='append',required=True);p.add_argument('--weight',type=int,default=600);a=p.parse_args()
 primary=TTFont(a.font)
 if 'fvar' in primary:primary=instantiateVariableFont(primary,{'wght':a.weight},inplace=True)
 if primary['OS/2'].usWeightClass!=a.weight:p.error('Primary font must match the requested weight')
 for candidate in a.fallback_font:
  if TTFont(candidate)['OS/2'].usWeightClass!=a.weight:p.error('Fallback fonts must be instantiated at the requested weight')
 small=ROOT/'src/ui/fonts';large=ROOT/'resources/ui-assets/fonts/large'
 body=points(small/'ui_font_text_14.c');title=points(small/'ui_font_portal_title_22.c');numbers=points(small/'ui_font_text_24.c')|points(small/'ui_font_text_28.c')
 specs={'small':{'body':[10,12],'title':[18,20],'number':[16,18,20,22,24,26],'ascii':[8]},'large':{'body':[14,16,18,20,22,24,26],'title':[32,36,40,42],'number':[32,36,40,44,48,52]}}
 bases={'small':{'body':('ui_font_text_14',14),'title':('ui_font_portal_title_22',22),'number24':('ui_font_text_24',24),'number28':('ui_font_text_28',28),'project':('ui_font_project_16',16)},'large':{'body':('ui_font_text_14',28),'title':('ui_font_portal_title_22',44),'number24':('ui_font_text_24',48),'number28':('ui_font_text_28',56)}}
 npx=shutil.which('npx.cmd') or shutil.which('npx')
 if not npx:p.error('Node.js/npx required')
 with tempfile.TemporaryDirectory(prefix='xtouch-native-') as temp:
  temp=Path(temp);f=temp/'primary.ttf';primary.save(f);paths=[f]+a.fallback_font;maps=[TTFont(path).getBestCmap() for path in paths]
  for profile,groups in specs.items():
   chunks=['/* Native pixel sizes. Generated by scripts/generate_native_fonts.py. */\n#include "lvgl.h"\n#include "ui/native_fonts.h"\n']
   for name,_ in bases[profile].values():chunks.append(f'LV_FONT_DECLARE({name});\n')
   fonts=[]
   for family,sizes in groups.items():
    codes=body if family=='body' else title if family=='title' else numbers if family=='number' else set(range(32,127))|numbers
    for size in sizes:
     name=f'ui_native_{family}_{size}';dest=temp/(name+'.c');parts=[[] for _ in paths]
     for code in sorted(codes):
      index=next((i for i,m in enumerate(maps) if code in m),None)
      if index is None:raise ValueError('Missing glyph '+hex(code))
      parts[index].append(code)
     cmd=[npx,'--yes','lv_font_conv@1.5.3','--size',str(size),'--bpp','4','--format','lvgl','--no-kerning','--lv-include','lvgl.h','--lv-font-name',name]
     for path,group in zip(paths,parts):
      if not group:continue
      cmd+=['--font',str(path)];ascii=[c for c in group if c<128];symbols=''.join(chr(c) for c in group if c>=128)
      if ascii:cmd+=['--range',ranges(ascii)]
      if symbols:cmd+=['--symbols',symbols]
      cmd+=['--autohint-strong']
     subprocess.run(cmd+['-o',str(dest)],check=True)
     text=dest.read_text('utf-8');text=re.sub(r'^ \* Opts:.*$',f' * Native {size}px, weight {a.weight}; generated by scripts/generate_native_fonts.py.',text,flags=re.M)
     text=re.sub(r'(?<!\.)\b(glyph_bitmap|glyph_dsc|cmaps|font_dsc|unicode_list_\d+)\b',lambda m:name+'_'+m.group(1),text)
     chunks.append(text);fonts.append((size,name,family));print(profile,name,len(codes),'glyphs',flush=True)
   chunks.append('''\nstatic bool covers(const lv_font_t *f,const char *text){
 uint32_t at=0;while(text[at]){uint32_t cp=_lv_txt_encoded_next(text,&at);if(cp<32)continue;lv_font_glyph_dsc_t d={0};if(!f->get_glyph_dsc(f,&d,cp,0)||d.is_placeholder)return false;}return true;
}
typedef struct {unsigned pixels;const lv_font_t *font;} NativeSize;
const lv_font_t *ui_native_font_select(const lv_font_t *source,unsigned zoom,const char *text){
 const NativeSize *sizes=NULL;unsigned count=0,pixels=0;
''')
   for family,(base,pixel) in bases[profile].items():
    available=[]
    if family=='body':available=[x for x in fonts if x[2] in ('body','ascii')]
    elif family=='title':available=[x for x in fonts if x[2] in ('body','title','ascii')]+[(bases[profile]['body'][1],bases[profile]['body'][0],'body')]
    elif family=='project':available=[x for x in fonts if x[2] in ('body','ascii')]+[(14,'ui_font_text_14','body')]
    else:available=[x for x in fonts if x[2] in ('body','number','ascii')]+[(bases[profile]['body'][1],bases[profile]['body'][0],'body')]
    if profile=='small' and family in ('title','number24','number28'):available.append((16,'ui_font_project_16','project'))
    available=sorted({(s,n) for s,n,_ in available if s<pixel},reverse=True)
    entries=','.join('{'+str(s)+',&'+n+'}' for s,n in available)
    if profile=='small' and family=='title':
     # Keep the 4 MB CYD OTA budget; use the native 18 px fallback instead.
     entries=entries.replace('{20,&ui_native_title_20},','\n#ifndef __XTOUCH_SCREEN_28__\n{20,&ui_native_title_20},\n#endif\n')
    chunks.append(f' static const NativeSize {family}[]={{'+entries+'};\n')
    chunks.append(f' if(source==&{base}){{sizes={family};count=sizeof({family})/sizeof(*{family});pixels={pixel};}}\n')
   chunks.append(' if(!sizes)return NULL;unsigned wanted=pixels*zoom/256;for(unsigned i=0;i<count;++i)if(sizes[i].pixels<=wanted&&covers(sizes[i].font,text))return sizes[i].font;return NULL;\n}\n')
   target=(small if profile=='small' else large)/'ui_font_native.c';target.write_text('\n'.join(chunks),'utf-8');print('Wrote',target.relative_to(ROOT),flush=True)
if __name__=='__main__':main()
