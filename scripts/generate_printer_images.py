"""Generate bounded, row-addressable RLE printer art (Pillow required).
Palette precision stays at 128 colors; only the currently drawn row is decoded.
"""
from pathlib import Path
from PIL import Image, ImageOps
import hashlib, struct, json
root = Path(__file__).resolve().parents[1]
assets = root / 'resources/printer-images'
SIZE = 112

def pack(row):
    out = bytearray(); x = 0
    while x < len(row):
        run = 1
        while x+run < len(row) and row[x+run] == row[x] and run < 128: run += 1
        if run >= 3:
            out.extend((0x80 | (run-1), row[x])); x += run
        else:
            start = x; x += run
            while x < len(row) and x-start < 128:
                run = 1
                while x+run < len(row) and row[x+run] == row[x] and run < 128: run += 1
                if run >= 3: break
                x += min(run, 128-(x-start))
            out.append(x-start-1); out.extend(row[start:x])
    return out

def unpack(data):
    out = bytearray(); i = 0
    while i < len(data):
        token = data[i]; i += 1; count = (token & 127)+1
        if token & 128: out.extend([data[i]]*count); i += 1
        else: out.extend(data[i:i+count]); i += count
    return out

lines = ['/* Generated by scripts/generate_printer_images.py; see resources/printer-images/NOTICE.md. */', '#include "../printer_models.h"']
seen = {}; sizes = {}
for path in sorted(assets.glob('printer_preview_*.png')):
    code = path.stem.removeprefix('printer_preview_')
    image = Image.open(path).convert('RGBA')
    box = image.getbbox()
    if box: image = image.crop(box)
    image = ImageOps.contain(image, (SIZE-8, SIZE-8), Image.Resampling.LANCZOS)
    canvas = Image.new('RGBA', (SIZE, SIZE), '#555555')
    canvas.alpha_composite(image, ((SIZE-image.width)//2, (SIZE-image.height)//2))
    indexed = canvas.convert('RGB').quantize(colors=128, method=Image.Quantize.MEDIANCUT)
    palette = indexed.getpalette(); palette += [0]*(384-len(palette))
    data = bytearray(b'XTP1'+bytes((SIZE, SIZE, 128, 0)))
    for i in range(128):
        r,g,b = palette[i*3:i*3+3]
        data.extend(struct.pack('<H', ((r>>3)<<11)|((g>>2)<<5)|(b>>3)))
    pixels = indexed.tobytes(); encoded = bytearray(); offsets = []
    for y in range(SIZE):
        row = pixels[y*SIZE:(y+1)*SIZE]; offsets.append(len(encoded))
        packed = pack(row); assert unpack(packed) == row
        encoded.extend(packed)
    offsets.append(len(encoded)); assert len(encoded) <= 65535
    data.extend(struct.pack('<'+'H'*len(offsets), *offsets)); data.extend(encoded)
    digest = hashlib.sha256(data).digest(); name = 'printer_pixels_'+code.replace('-','_')
    if digest not in seen:
        seen[digest] = name
        lines.append('static const uint8_t '+name+'[] = {')
        lines.extend(','.join('0x%02x'%v for v in data[i:i+24])+',' for i in range(0,len(data),24))
        lines.append('};')
    name = seen[digest]; sizes[code] = len(data)
    lines.append('const lv_img_dsc_t printer_image_'+code.replace('-','_')+' = { .header = { .cf = LV_IMG_CF_RAW, .w = '+str(SIZE)+', .h = '+str(SIZE)+' }, .data_size = '+str(len(data))+', .data = '+name+' };')
stored_bytes = sum(sizes[k] for k in sizes if 'printer_pixels_'+k.replace('-','_') in seen.values())
assert stored_bytes <= 128*1024, 'Printer artwork exceeds the 128 KiB resource budget'
(root/'src/ui/images/printer_models.c').write_text('\n'.join(lines)+'\n', encoding='utf-8')
print(json.dumps({'models':len(sizes), 'unique_images':len(seen), 'stored_bytes':stored_bytes, 'sizes':sizes}, indent=2))
