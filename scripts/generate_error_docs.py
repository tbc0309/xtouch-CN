"""Generate searchable fault documentation and only the small UI action rules.

The full vendor text and code database stays under docs; firmware contains no
message corpus or known-code whitelist, so new nonzero codes still display.
"""
from pathlib import Path
import json,re
ROOT=Path(__file__).resolve().parents[1]
source=json.loads((ROOT/'docs/data/error-codes.json').read_text(encoding='utf-8'))
def write(path,text):
 if not path.exists() or path.read_text(encoding='utf-8')!=text:path.write_text(text,encoding='utf-8')
parts=['/* Generated action rules only; descriptions live in docs/data/error-codes.json. */','#pragma once','#include <stdint.h>']
for kind in ['retry']:
 values=sorted({v.upper() for v in source[kind]});assert all(re.fullmatch(r'[0-9A-Fa-f]{8}',v) for v in values)
 parts.append('static const uint32_t '+kind+'_codes[]={'+(','.join('0x'+v.upper()+'U' for v in sorted(values)) or '0U')+'};')
parts.append('typedef struct { uint32_t code; unsigned char device,flags; } XTouchErrorAction;')
devices=sorted(source.get('deviceActions',{}));parts.append('static const char error_action_devices[][4]={'+','.join(json.dumps(d) for d in devices)+'};')
rows=[]
for index,dev in enumerate(devices):
 for code,actions in source['deviceActions'][dev]:
  if len(code)!=8:continue
  flags=(1 if 8 in actions or 9 in actions else 0)|(2 if 7 in actions else 0)
  if flags:rows.append((index,int(code,16),flags))
parts.append('static const XTouchErrorAction error_action_rows[]={'+','.join('{0x%08XU,%u,%u}'%(code,index,flags) for index,code,flags in sorted(set(rows)))+'};')
write(ROOT/'src/xtouch/bbl/error_actions.h','\n'.join(parts)+'\n')
for kind,name,title in [('hms','HMS-CODES.md','HMS 故障码 / HMS codes'),('device','PRINT-ERROR-CODES.md','打印错误码 / Print error codes')]:
 rows=[]
 for key,text in source[kind]:
  digits=16 if kind=='hms' else 8
  assert re.fullmatch(r'[0-9A-Fa-f]{'+str(digits)+'}',key)
  value=int(key,16);canonical=f'{value:0{digits}X}'
  display='HMS '+'-'.join(canonical[i:i+4] for i in range(0,16,4)) if kind=='hms' else '0x'+canonical
  rows.append((value,canonical,display,text))
 assert len({r[0] for r in rows})==len(rows),'Duplicate error code'
 folder=ROOT/'docs/errors'/kind;folder.mkdir(parents=True,exist_ok=True);expected=set()
 index=['# '+title,'','[故障码说明 / Error code guide](ERROR-CODES.md)','','共 '+str(len(rows))+' 个代码，按前两位分组；每页最多 150 条，使用浏览器搜索。文案随设备与固件版本变化。','','Grouped by code prefix, up to 150 entries per page. Descriptions vary by model and firmware.','','| 代码前缀 / Prefix | 对照 / Lookup |','| --- | --- |']
 groups={}
 for row in sorted(rows):groups.setdefault(row[1][:2],[]).append(row)
 for prefix,group in groups.items():
  for start in range(0,len(group),150):
   page=prefix+'-'+str(start//150+1)+'.md';expected.add(page)
   lines=['<!-- Generated by scripts/generate_error_docs.py -->','# '+title+' · '+prefix,'','[返回索引 / Index](../../'+name+') | [故障码说明 / Guide](../../ERROR-CODES.md)','','同码可能因机型不同而有不同文案。来源和原始变体见 `docs/data/error-codes.json`。 Model-specific descriptions and source variants are preserved in that data file.','','| 屏幕错误码 / Code | 中文说明 / Chinese | English description |','| --- | --- | --- |']
   for value,key,display,text in group[start:start+150]:
    zh=source.get('zh',{}).get(kind,{}).get(key,'')
    escape=lambda v:v.replace('|','\\|').replace('\n','<br>')
    lines.append('| `'+display+'` | '+escape(zh)+' | '+escape(text)+' |')
   write(folder/page,'\n'.join(lines)+'\n')
   index.append('| `'+prefix+'` | [第 '+str(start//150+1)+' 页 / Page '+str(start//150+1)+'](errors/'+kind+'/'+page+') · '+str(len(group[start:start+150]))+' 条 / entries |')
 for previous in folder.glob('*.md'):
  if previous.name not in expected and previous.read_text('utf-8').startswith('<!-- Generated by scripts/generate_error_docs.py -->'):previous.unlink()
 write(ROOT/'docs'/name,'\n'.join(index)+'\n')
print(f'Error docs: {len(source["hms"])} HMS + {len(source["device"])} print errors; descriptions excluded from firmware')
