"""Generate W7 LVGL subsets. Does not modify application source or translations.

Set XTOUCH_W7_FONT to the local TTF path. Node.js/npx is required.
"""
from pathlib import Path
import os
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
FONT_PATH = Path(os.environ.get('XTOUCH_W7_FONT', 'Tencent-W7.ttf'))


def generate_font(name, size, characters, fallback, font_path=FONT_PATH, supplemental=''):
    if not font_path.is_file():
        raise SystemExit(f'Set XTOUCH_W7_FONT to your Tencent W7 TTF: {FONT_PATH}')
    npx = shutil.which('npx.cmd') or shutil.which('npx')
    if not npx:
        raise SystemExit('Node.js/npx is required')
    codes = sorted({ord(ch) for ch in characters})
    command=[
        npx, '--yes', 'lv_font_conv@1.5.3', '--font', str(font_path),
        '--size', str(size), '--bpp', '4', '--format', 'lvgl',
        '--range', ','.join(f'0x{cp:x}' for cp in codes),
    ]
    if supplemental:
        latin=Path(os.environ.get('XTOUCH_LATIN_FONT','Inter-Regular.ttf'))
        if not latin.is_file():raise SystemExit('Set XTOUCH_LATIN_FONT to the OFL Inter Regular font')
        hangul={ch for ch in supplemental if 0xAC00<=ord(ch)<=0xD7AF or 0x1100<=ord(ch)<=0x11FF or 0x3130<=ord(ch)<=0x318F}
        other=set(supplemental)-hangul
        if other:command+=['--font',str(latin),'--range',','.join(f'0x{ord(ch):x}' for ch in sorted(other))]
        if hangul:
            korean=Path(os.environ.get('XTOUCH_KOREAN_FONT','AlibabaSansKR-Medium.ttf'))
            if not korean.is_file():raise SystemExit('Set XTOUCH_KOREAN_FONT to Alibaba Sans KR Medium')
            command+=['--font',str(korean),'--range',','.join(f'0x{ord(ch):x}' for ch in sorted(hangul))]
    command += [
        '--autohint-strong', '--no-kerning', '--lv-include', '../ui.h',
        '--lv-font-name', name, '--lv-fallback', fallback,
        '-o', str(ROOT / f'src/ui/fonts/{name}.c'),
    ]
    subprocess.run(command, check=True)
    output = ROOT / f'src/ui/fonts/{name}.c'
    source = output.read_text('utf-8')
    source = re.sub(r'^ \* Opts:.*$', ' * Generated by scripts/localize_zh.py (LVGL font converter 1.5.3).', source, flags=re.M)
    if name == 'ui_font_tencent_w7_14':
        # Keep every language on the established UI baseline and line spacing.
        source = re.sub(r'\.line_height = \d+', '.line_height = 19', source)
        source = re.sub(r'\.base_line = \d+', '.base_line = 5', source)
    output.write_text(source.rstrip() + '\n', 'utf-8')
    return len(codes)


if __name__ == '__main__':
    text = '\n'.join(p.read_text('utf-8-sig') for p in (ROOT / 'src').rglob('*')
                     if p.suffix in ('.c', '.cpp', '.h') and 'fonts' not in p.parts)
    strings = re.findall(r'"((?:\\.|[^"\\])*)"', text)
    from fontTools.ttLib import TTFont
    chars = ''.join(chr(cp) for cp in range(32,127))
    chars += ''.join(ch for value in strings for ch in value if ord(ch)>=160 and ch.isprintable())
    cmap=TTFont(FONT_PATH).getBestCmap()
    primary=''.join(ch for ch in chars if ord(ch) in cmap)
    supplemental=''.join(ch for ch in chars if ord(ch) not in cmap)
    small=generate_font('ui_font_tencent_w7_14',14,primary,'lv_font_montserrat_14',supplemental=supplemental)
    large = generate_font('ui_font_tencent_w7_28', 28, '0123456789.-+/%:°NAC ', 'lv_font_montserrat_28')
    generate_font('ui_font_tencent_w7_24', 24, '0123456789.- ', 'lv_font_montserrat_14')
    import json
    locales=json.loads((ROOT/'resources/ui-locales.json').read_text('utf-8'))
    qr_chars=''.join(''.join(locales[key]) for key in ('Scan to join Wi-Fi','Scan to manage'))
    qr_primary=''.join(ch for ch in qr_chars if ord(ch) in cmap)
    qr_extra=''.join(ch for ch in qr_chars if ord(ch) not in cmap)
    generate_font('ui_font_portal_title_22',22,qr_primary,'ui_font_tencent_w7_14',supplemental=qr_extra)
    print(f'Tencent W7: {small} UI glyphs, {large} numeric glyphs')
